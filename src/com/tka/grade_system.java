package com.tka;

public class grade_system {
	public static void main (String Args[]) {
		char grade ='A';
		switch(grade) {
		case'A':
			System.out.println("Excellent");
			break;
		case'B':
			System.out.println("Good");
			break;
		case'C':
			System.out.println("Average");
			break;
		case'D':
			System.out.println("Pass");
			break;
		case'E':
			System.out.println("Fail");
			break;
			
		}
		
	}

}
